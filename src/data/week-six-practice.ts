export function getWeekSixPrompt(
  routeId: WeekSixRouteId,
  industry: string,
  sourceTab: string,
  task: string,
): string {
  const route = WEEK_SIX_ROUTES.find(({ id }) => id === routeId);
  if (!route) throw new Error("조사 유형을 선택해 주세요.");

  return [
    "미국 브랜드 웹사이트 리디자인을 위한 조사표를 구성해줘.",
    `관심 업종: ${industry.trim() || "기존 자료에서 파악하고, 자료가 없다면 먼저 내 관심 업종을 물어봐줘."}`,
    `기존 자료: ${sourceTab.trim() || (routeId === "c" ? "없음" : "첨부하거나 현재 파일에서 확인할 수 있는 조사 탭")}`,
    `비교할 사용자 행동: ${task.trim() || "선택한 업종의 방문자가 같은 조건에서 수행할 수 있는 행동 하나를 제안해줘. 완료 여부를 확인할 수 있는 문장으로 적어줘."}`,
    "",
    route.prompt,
    "",
    "기존 탭과 개인 심화 자료를 보존해줘. 다음 이름의 탭이 있으면 비어 있는 항목을 채우고, 없으면 만들어줘. 시트를 직접 편집할 수 없다면 같은 열 순서로 복사할 수 있는 표를 제공해줘.",
    "01 미국 브랜드 조사 — 브랜드명 / 세부 업종 / 설립 국가·근거 URL / 브랜드 유형 / 미국 공식 사이트 URL / 살펴볼 페이지 URL / 내 관찰. 미국에서 출발한 서로 다른 브랜드를 10곳 이상 담아줘. 해외 브랜드의 미국 사이트는 참고 사례로 따로 구분해줘.",
    "02 리디자인 후보 비교 — 후보 3곳 / 공통 사용자 행동 / 조사할 화면 URL / Gemini 추천 이유 / 내 화면 캡처 / 내가 관찰한 사실 / 예상되는 어려움 / 유지할 브랜드 요소 / 개선 가설. 추천 이유에는 어느 화면에서 무엇을 직접 확인하면 좋을지 적어줘.",
    "03 최종 선정과 기획 방향 — 최종 브랜드 / 선택 이유 / 대상 사용자와 핵심 행동 / 유지할 특징 / 개선할 화면 / 배포 후 확인할 행동을 적을 칸을 만들어줘.",
    "확인하지 못한 출처나 주소는 ‘확인 필요’로 표시해줘. 직접 관찰, 캡처, 최종 선택과 기획 방향은 내가 작성할 수 있도록 빈칸으로 둬. 결과는 한국어로, 브랜드명과 메뉴명은 원문으로 써줘.",
  ].join("\n");
}
